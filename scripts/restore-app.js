import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const a = fs.readFileSync(path.join(__dirname, "app.b64.1"), "utf8");
const b = fs.readFileSync(path.join(__dirname, "app.b64.2"), "utf8");
const b64 = (a + b).replace(/\s+/g, "");
const out = path.join(__dirname, "..", "src", "App.jsx");
fs.writeFileSync(out, Buffer.from(b64, "base64"));
console.log("restored App.jsx", fs.statSync(out).size, "bytes");
